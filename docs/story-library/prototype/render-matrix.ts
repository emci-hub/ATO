/**
 * Renders the full combo matrix and writes sample-output.md.
 * Exits 1 when any render fails. Run:
 *   npx tsx docs/story-library/prototype/render-matrix.ts
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';

import { validateLibrary } from './validate';

const outPath = path.join(path.dirname(new URL(import.meta.url).pathname), 'sample-output.md');

function label(row: { template: { id: string }; reader: { dominant: { trait: string; tier: string }; secondary?: { trait: string; tier: string }; pronoun: { id: string } } }): string {
  const second = row.reader.secondary ? ` + ${row.reader.secondary.trait} ${row.reader.secondary.tier}` : '';
  return `${row.template.id} · ${row.reader.dominant.trait} ${row.reader.dominant.tier}${second} · ${row.reader.pronoun.id}`;
}

const report = validateLibrary();
const highlights = [
  'insight-ping',
  'insight-keep',
  'legend-room',
  'legend-detour',
].flatMap((id) => {
  const match = report.cases.find(
    (row) =>
      row.template.id === id &&
      row.reader.dominant.trait === 'openness' &&
      row.reader.dominant.tier === 'high' &&
      row.reader.pronoun.id === 'she' &&
      !row.reader.secondary,
  );
  return match ? [match] : [];
});
const combo = report.cases.find(
  (row) =>
    row.template.id === 'legend-detour' &&
    row.reader.dominant.trait === 'openness' &&
    row.reader.dominant.tier === 'high' &&
    row.reader.secondary?.trait === 'playfulness' &&
    row.reader.secondary.tier === 'high' &&
    row.reader.pronoun.id === 'they',
);
const cautious = report.cases.find(
  (row) =>
    row.template.id === 'legend-detour' &&
    row.reader.dominant.trait === 'steadiness' &&
    row.reader.dominant.tier === 'low' &&
    row.reader.pronoun.id === 'he' &&
    !row.reader.secondary,
);

const lines: string[] = [];
lines.push('# Story library sample matrix');
lines.push('');
lines.push(`Library \`storylib-0\`. ${report.cases.length} renders. Failures: ${report.failures.length}. Extra notes: ${report.notes.length}.`);
lines.push('');
lines.push('This file is generated by `render-matrix.ts`. Do not hand-edit it.');
lines.push('');
lines.push('## Highlighted');
lines.push('');
for (const row of [...highlights, combo, cautious].filter((row): row is NonNullable<typeof row> => row != null)) {
  lines.push(`### ${label(row)}`);
  lines.push('');
  if (row.result.endingId) lines.push(`Ending: \`${row.result.endingId}\`.`);
  lines.push('');
  lines.push(row.result.text);
  lines.push('');
}
if (report.notes.length > 0) {
  lines.push('## Notes');
  lines.push('');
  for (const note of report.notes) lines.push(`- ${note}`);
  lines.push('');
}
if (report.failures.length > 0) {
  lines.push('## Failures');
  lines.push('');
  for (const row of report.failures) {
    lines.push(`- ${label(row)}: ${row.result.issues.map((issue) => `${issue.code} (${issue.detail})`).join('; ')}`);
  }
  lines.push('');
}
lines.push('## Full matrix');
lines.push('');
for (const row of report.cases) {
  lines.push(`### ${label(row)}`);
  lines.push('');
  if (row.result.endingId) lines.push(`Ending: \`${row.result.endingId}\`.`);
  lines.push('');
  lines.push(row.result.text);
  lines.push('');
}

writeFileSync(outPath, lines.join('\n'));

const ok = report.failures.length === 0 && report.notes.length === 0;
console.log(`${ok ? 'ok' : 'fail'}: ${report.cases.length} renders, ${report.failures.length} failures, ${report.notes.length} notes`);
console.log(`wrote ${outPath}`);
if (!ok) {
  for (const note of report.notes) console.log(`note: ${note}`);
  for (const row of report.failures.slice(0, 12)) {
    console.log(`fail ${label(row)}: ${row.result.issues.map((issue) => `${issue.code}:${issue.detail}`).join('; ')}`);
  }
  process.exit(1);
}
