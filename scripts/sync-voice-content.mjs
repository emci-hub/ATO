// Reads the canonical voice content files and emits a TS module the app can
// import at runtime (React Native has no fs access to the repo). The .txt/.md
// files stay the source of truth — re-run `npm run sync:voice` after editing.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'src', 'lib', 'voice');
const outPath = join(outDir, 'content.generated.ts');

const voice = readFileSync(join(root, 'src', 'content', 'voice', 'voice-reference.txt'), 'utf8');
const library = readFileSync(join(root, 'src', 'content', 'copy', 'library.md'), 'utf8');

mkdirSync(outDir, { recursive: true });

const ts = `// AUTO-GENERATED by scripts/sync-voice-content.mjs — do not edit by hand.
// Source of truth: src/content/voice/voice-reference.txt and src/content/copy/library.md.
// Re-run \`npm run sync:voice\` after editing those files.
// (BANK_MARKDOWN / first_cards.md, the old Day 1-3 Read+Do cards, were removed in roadmap A5.)

export const VOICE_REFERENCE_TEXT: string = ${JSON.stringify(voice)};

export const LIBRARY_MARKDOWN: string = ${JSON.stringify(library)};
`;

writeFileSync(outPath, ts, 'utf8');
console.log(`Wrote ${outPath}`);
