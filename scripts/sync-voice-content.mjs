// Reads the canonical voice content files and emits a TS module the app can
// import at runtime (React Native has no fs access to the repo). The .txt/.md
// files stay the source of truth — re-run `npm run sync:voice` after editing.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'src', 'lib', 'voice');
const outPath = join(outDir, 'content.generated.ts');

const sage = readFileSync(join(root, 'src', 'app', 'voice', 'sage.txt'), 'utf8');
const bank = readFileSync(join(root, 'src', 'app', 'copy', 'first_cards.md'), 'utf8');

mkdirSync(outDir, { recursive: true });

const ts = `// AUTO-GENERATED by scripts/sync-voice-content.mjs — do not edit by hand.
// Source of truth: src/app/voice/sage.txt and src/app/copy/first_cards.md.
// Re-run \`npm run sync:voice\` after editing those files.

export const SAGE_VOICE: string = ${JSON.stringify(sage)};

export const BANK_MARKDOWN: string = ${JSON.stringify(bank)};
`;

writeFileSync(outPath, ts, 'utf8');
console.log(`Wrote ${outPath}`);
