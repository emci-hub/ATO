/**
 * Thin one-release wrapper. New work uses `npm run art:pack` + `art:registry`.
 * Writes `assets/play/skins/streetwear/skin.json` from the packed Streetwear
 * sheets' `meta.json` (run after `play-art-pack.ts --skin streetwear`).
 *
 * Every role mirrors the cast role it replaces. `units` is scaled so the
 * Streetwear figure's visible body is the same height on screen as the cast
 * figure's (cast body ratio / Streetwear body ratio), and `footAt` is the
 * measured feet line, so nothing floats or shrinks when the skin switches.
 *
 * Usage: npx tsx scripts/streetwear-skin-gen.ts
 */
import fs from 'node:fs';
import path from 'node:path';

import { PNG } from 'pngjs';

type CharMeta = { footAt: number; bodyRatio: number; clips: Record<string, number> };
type Role = Record<string, unknown>;

const repo = path.resolve(__dirname, '..');
const meta = JSON.parse(fs.readFileSync(path.join(repo, 'assets/play/sheets/streetwear/meta.json'), 'utf8')) as {
  chars: Record<string, CharMeta>;
};
const cast = JSON.parse(fs.readFileSync(path.join(repo, 'assets/play/skins/cast/skin.json'), 'utf8')) as {
  roles: Record<string, Role & { keys: string[]; units: number }>;
};

const ROTATIONS = ['north', 'north-east', 'east', 'south-east', 'south', 'south-west', 'west', 'north-west'];

/** Visible body height / frame height of a cast role's east rotation. */
function castBodyRatio(role: string): number {
  const east = cast.roles[role].keys.find((k) => k.endsWith('/east'));
  if (!east) throw new Error(`${role}: no east key`);
  const png = PNG.sync.read(fs.readFileSync(path.join(repo, 'assets/play', `${east}.png`)));
  let y0 = png.height;
  let y1 = -1;
  for (let y = 0; y < png.height; y += 1) {
    for (let x = 0; x < png.width; x += 1) {
      if (png.data[(y * png.width + x) * 4 + 3] > 8) {
        y0 = Math.min(y0, y);
        y1 = Math.max(y1, y);
      }
    }
  }
  return (y1 - y0 + 1) / png.height;
}

function clip(base: string, name: string, frames: number) {
  return { dirs: 2, order: ['east', 'west'], frames, base: `${base}/animations/${name}` };
}

function charRole(role: string, char: string, map: { walk?: string; anims?: Record<string, string> }): Role {
  const m = meta.chars[char];
  if (!m) throw new Error(`no packed character ${char}`);
  const base = `skins/streetwear/${char}`;
  const castRole = cast.roles[role];
  const out: Role = {
    keys: ROTATIONS.map((d) => `${base}/rotations/${d}`),
    dirs: 8,
    pivot: 'feet',
    footAt: m.footAt,
    cellPx: castRole.cellPx,
    units: Number(((castRole.units * castBodyRatio(role)) / m.bodyRatio).toFixed(2)),
  };
  if (castRole.scales) out.scales = castRole.scales;
  if (map.walk) {
    const n = m.clips[map.walk];
    if (!n) throw new Error(`${char}: no ${map.walk} clip`);
    out.walk = clip(base, map.walk, n);
  }
  if (map.anims) {
    const anims: Record<string, unknown> = {};
    for (const [slot, name] of Object.entries(map.anims)) {
      const n = m.clips[name];
      if (!n) throw new Error(`${char}: no ${name} clip`);
      anims[slot] = clip(base, name, n);
    }
    out.anims = anims;
  }
  return out;
}

const creep = { walk: 'Walk', anims: { idle: 'Idle', death: 'Death' } };
const roles: Record<string, Role> = {
  'unit.puff': charRole('unit.puff', 'creeps/village-girl', creep),
  'unit.runner': charRole('unit.runner', 'creeps/wizard', creep),
  'unit.tank': charRole('unit.tank', 'creeps/knight', creep),
  // Towers keep static rotations here; their Idle/Attack clips are overlaid by
  // `towerSkinRole` (skin.ts), exactly like the cast towers.
  'tower.archer': charRole('tower.archer', 'towers/viper', {}),
  'tower.vine': charRole('tower.vine', 'towers/ghost', {}),
  'tower.crystal': charRole('tower.crystal', 'towers/lux', {}),
  'unit.boss_scout': charRole('unit.boss_scout', 'boss/oni', { walk: 'Walk', anims: { idle: 'Idle', death: 'Death' } }),
  // Heroes have no Death clip; Hurt is the closest fall (cast uses a flinch too).
  'unit.final': charRole('unit.final', 'heroes/archangel', { walk: 'Walk', anims: { idle: 'Idle', death: 'Hurt' } }),
  'unit.avatar': charRole('unit.avatar', 'heroes/corvus', {
    walk: 'Walk',
    anims: { idle: 'Idle', attack: 'Attack', skill: 'Skill', hurt: 'Hurt', dash: 'Dash' },
  }),
};

const skin = {
  $comment:
    'GENERATED by scripts/streetwear-skin-gen.ts from the packed sheets meta — do not edit by hand. Drawn only from sheets/streetwear (loose frames are not bundled). Only active when PlaySettings.artSkin is "streetwear".',
  pack: 'streetwear',
  roles,
};
const out = path.join(repo, 'assets/play/skins/streetwear/skin.json');
fs.writeFileSync(out, `${JSON.stringify(skin, null, 2)}\n`);
console.log(`wrote ${path.relative(repo, out)} (${Object.keys(roles).length} roles)`);
